import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseCsv,parseExternalResources} from './build-catalogue.mjs';
import {loadCanonicalResources,toCatalogueEntry} from './canonical-source.mjs';
import {githubVersion,externalVersions} from './version-evidence.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.resolve(root,p),'utf8'));
const index=process.argv.indexOf('--github');
if(index<0||!process.argv[index+1])throw Error('Supply --github with reviewed output from check-updates.mjs --github');
const fetched=read(process.argv[index+1]);
const canonical=fs.existsSync(path.join(root,'data/resources/index.json'))?loadCanonicalResources(root):null;
const sourceEntries=canonical?canonical.map(toCatalogueEntry):[...parseCsv(fs.readFileSync(path.join(root,'data/repositories.csv'),'utf8')), ...parseExternalResources(fs.readFileSync(path.join(root,'data/external-tools.md'),'utf8'))];
const repos=sourceEntries.filter(e=>e.repository);
const external=sourceEntries.filter(e=>!e.repository);
const audit=read('data/update-audit.json'),community=read('data/community-discoveries.json');
const entries=repos.map(e=>{
 const item=fetched.find(x=>x.repository===e.repository);
 return githubVersion(e.repository,e.url,item);
});
entries.push(...externalVersions(external,audit,community,read('data/version-overrides.json')));
fs.writeFileSync(path.join(root,'data/versions.json'),JSON.stringify({schema_version:1,entries},null,2)+'\n');
console.log(`Recorded ${entries.length} version states.`);
